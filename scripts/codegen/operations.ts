/**
 * Every TMDB read operation tmdbkit implements, with the names a person chose (the spec's `operationId`s are inconsistent and sometimes wrong: `details-copy` is the network alternative-names endpoint). `scripts/codegen/scaffold.ts` reads this to write op files and specs that don't exist yet, and it doubles as Phase 3's checklist.
 *
 * - `path` is the spec's path (it also names the docs page: `docs` is the operationId slug used by developer.themoviedb.org/reference/<docs>).
 * - `fixture` is the operation key in `packages/tmdbkit/fixtures/` (absent for the `latest` endpoints, which aren't recorded).
 * - `output` is the exported name of the response schema (without the `Schema` suffix), and `outputFrom` the module it lives in, relative to `src/`.
 */
export interface Operation {
  name: string;
  domain: string;
  path: string;
  docs: string;
  title: string;
  fixture?: string;
  output: string;
  outputFrom: string;
  /** The `append_to_response` methods the endpoint accepts (each typed as an optional key on the output). */
  appendable?: readonly string[];
}

